// Input colours differ in lightness so that A, B and "both" (black) stay distinct in greyscale;
// both keep a contrast ratio above 4.5 against the cell background.
const C={ink:'#000000',muted:'#6b6b6b',A:'#1a3d8f',B:'#b85200',border:'#000000',head:'#e5e5e5',body:'#f6f6f6',corner:'#d5d5d5',changed:'#f2d98a',white:'#ffffff'};
const esc=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
// Variables are set in italic, as in the text; {m:'...'} marks a math segment.
const italic=s=>esc(s).replace(/[A-Za-z]+/g,w=>`<tspan font-style="italic">${w}</tspan>`);
const rich=s=>Array.isArray(s)?s.map(p=>typeof p==='string'?esc(p):italic(p.m)).join(''):(typeof s==='object'?italic(s.m):esc(s));
const T=(x,y,s,size=14,o={})=>`<text x="${x}" y="${y}" text-anchor="middle" font-size="${size}" fill="${C[o.color||'ink']}">${rich(s)}</text>`;
let edges=[],groups=[];
const box=(id,x,y,w,h,color='border',fill='white',radius=5)=>`<rect data-box="${id}" x="${x}" y="${y}" width="${w}" height="${h}" rx="${radius}" fill="${C[fill]}" stroke="${C[color]}" stroke-width="1.05"/>`;
const arrow=(from,to,x,y,X,Y,color='ink')=>{edges.push({from,to,start:[x,y],end:[X,Y]});return `<path d="M${x},${y}L${X},${Y}" fill="none" stroke="${C[color]}" stroke-width="1.15" marker-end="url(#arrow)"/>`;};
const windowText=(x,y,label,t,color='ink',size=18)=>`<text x="${x}" y="${y}" text-anchor="middle" font-size="${size}" fill="${C[color]}">${rich(label)}${t.blocks.map((b,i)=>`<tspan data-waning="${t.waxing_waning[i]}">[${b.join(', ').replaceAll('-','−')}]</tspan>${i<t.blocks.length-1?' ':''}`).join('')}</text>`;
function matrix(x,y,m,w,h,g,outlined=false,provenance=false){
 let out='';const n=m.length;
 for(let row=0;row<=n;row++)for(let col=0;col<=n;col++){
  const xx=x+col*(w+g),yy=y+row*(h+g),c=row&&col?m[row-1][col-1]:null;
  const text=row===0?(col===0?[{m:'a'},' / ',{m:'r'}]:String(col-1)):col===0?String(row-1):c.values.length?'['+c.values.join(',')+']'+(c.star?'*':''):'∅';
  const changed=outlined&&row&&col&&data.changed_cells.some(([a,b])=>a===row-1&&b===col-1);
  const fill=row===0?(col===0?'corner':'head'):col===0?'head':changed?'changed':'body';
  let color=row&&col&&!c.values.length?'muted':'ink';
  if(provenance&&row&&col&&c.values.length){
    const a=data.inversion_A[row-1][col-1],b=data.inversion_B[row-1][col-1];
    const eq=(u,v)=>JSON.stringify(u)===JSON.stringify(v);
    if(eq(c,a)&&!eq(c,b))color='A';
    if(eq(c,b)&&!eq(c,a))color='B';
  }
  out+=`<rect data-cell="true" x="${xx}" y="${yy}" width="${w}" height="${h}" fill="${C[fill]}"/>`;
  if(changed)out+=`<rect x="${xx+.6}" y="${yy+.6}" width="${w-1.2}" height="${h-1.2}" fill="none" stroke="${C.ink}" stroke-width="1.1"/>`;
  const size=14;
  out+=T(xx+w/2,yy+h/2+size*.31,text,size,{color});
 }
 return out;
}
